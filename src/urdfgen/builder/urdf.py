"""URDF XML generation from an :class:`ExpandedRobot`.

The document is built with :mod:`xml.etree.ElementTree`. String templating is
forbidden (spec section 6.3): it cannot escape attribute values correctly and
makes malformed output easy to produce.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from collections.abc import Iterable
from datetime import UTC, datetime

from urdfgen.builder.expand import ExpandedJoint, ExpandedLink, ExpandedRobot
from urdfgen.catalog.loader import Catalog
from urdfgen.catalog.schema import (
    BoxGeometry,
    CylinderGeometry,
    Geometry,
    Inertial,
    MeshGeometry,
    Origin,
    SphereGeometry,
)

DEFAULT_PACKAGE_NAME = "urdfgen_description"

FLOAT_PRECISION = 6
"""Significant digits for every number written to the URDF (spec section 6.3)."""


def format_float(value: float) -> str:
    """Format one number: 6 significant digits, with ``-0`` normalised to ``0``."""
    text = f"{value:.{FLOAT_PRECISION}g}"
    return "0" if text in {"-0", "-0.0"} else text


def format_vector(values: Iterable[float]) -> str:
    return " ".join(format_float(value) for value in values)


def build_urdf(
    robot: ExpandedRobot,
    catalog: Catalog,
    *,
    package_name: str = DEFAULT_PACKAGE_NAME,
    source_text: str | None = None,
    timestamp: datetime | None = None,
) -> ET.ElementTree:
    """Build the URDF document for ``robot``.

    ``timestamp`` is injectable so that tests can compare byte-for-byte against
    a golden file.
    """
    root = ET.Element("robot", {"name": robot.name})
    for comment in _provenance(robot, source_text, timestamp):
        root.append(ET.Comment(comment))

    for material in _materials_used(robot, catalog):
        root.append(material)
    for link in robot.links:
        root.append(_link_element(link, package_name))
    for joint in robot.joints:
        root.append(_joint_element(joint))

    ET.indent(root, space="  ")
    return ET.ElementTree(root)


def to_string(tree: ET.ElementTree) -> str:
    """Serialise a URDF document, with an XML declaration and trailing newline."""
    root = tree.getroot()
    if root is None:
        msg = "cannot serialise an empty document"
        raise ValueError(msg)
    body = ET.tostring(root, encoding="unicode")
    return f'<?xml version="1.0"?>\n{body}\n'


def build_urdf_string(
    robot: ExpandedRobot,
    catalog: Catalog,
    *,
    package_name: str = DEFAULT_PACKAGE_NAME,
    source_text: str | None = None,
    timestamp: datetime | None = None,
) -> str:
    return to_string(
        build_urdf(
            robot,
            catalog,
            package_name=package_name,
            source_text=source_text,
            timestamp=timestamp,
        )
    )


def mesh_uri(module_id: str, mesh_path: str, package_name: str) -> str:
    """Rewrite a module-relative mesh path to a ``package://`` URI (spec 6.3)."""
    filename = mesh_path.rsplit("/", 1)[-1]
    return f"package://{package_name}/meshes/{module_id}/{filename}"


# --- document sections ----------------------------------------------------


def _provenance(
    robot: ExpandedRobot, source_text: str | None, timestamp: datetime | None
) -> list[str]:
    """Header comments recording what produced this file (spec section 6.3)."""
    moment = (timestamp or datetime.now(UTC)).isoformat(timespec="seconds")
    modules = ", ".join(f"{module_id}@{version}" for module_id, version in robot.modules_used)
    comments = [
        " Generated by urdfgen. Do not edit by hand. ",
        f" generated: {moment} ",
        f" modules: {modules} ",
    ]
    if source_text:
        comments.append(f" input: {_sanitise_comment(source_text)} ")
    return comments


def _sanitise_comment(text: str) -> str:
    """Make arbitrary user text safe inside an XML comment.

    ``--`` terminates a comment early, and the input text comes from a user
    prompt, so it cannot be trusted to be comment-safe.
    """
    collapsed = " ".join(text.split())
    while "--" in collapsed:
        collapsed = collapsed.replace("--", "-")
    return collapsed.removesuffix("-")


def _materials_used(robot: ExpandedRobot, catalog: Catalog) -> list[ET.Element]:
    """Emit each referenced material exactly once (spec section 6.3)."""
    names: list[str] = []
    for link in robot.links:
        for name in (link.material, link.visual.material if link.visual else None):
            if name is not None and name in catalog.materials and name not in names:
                names.append(name)

    elements: list[ET.Element] = []
    for name in sorted(names):
        element = ET.Element("material", {"name": name})
        ET.SubElement(element, "color", {"rgba": format_vector(catalog.materials[name].rgba)})
        elements.append(element)
    return elements


def _link_element(link: ExpandedLink, package_name: str) -> ET.Element:
    element = ET.Element("link", {"name": link.name})

    if link.inertial is not None:
        element.append(_inertial_element(link.inertial))

    if link.visual is not None:
        visual = ET.SubElement(element, "visual")
        _append_origin(visual, link.visual.origin)
        visual.append(_geometry_element(link.visual.geometry, link.module_id, package_name))
        material = link.visual.material or link.material
        if material is not None:
            ET.SubElement(visual, "material", {"name": material})

    if link.collision is not None:
        collision = ET.SubElement(element, "collision")
        _append_origin(collision, link.collision.origin)
        collision.append(_geometry_element(link.collision.geometry, link.module_id, package_name))

    return element


def _inertial_element(inertial: Inertial) -> ET.Element:
    element = ET.Element("inertial")
    _append_origin(element, inertial.origin)
    ET.SubElement(element, "mass", {"value": format_float(inertial.mass)})
    if inertial.inertia is None:
        # expand.resolve_inertial fills this in for every primitive link, so a
        # None here means the module declared mass without a derivable tensor.
        msg = "inertial has no inertia tensor; expansion should have resolved it"
        raise ValueError(msg)
    tensor = inertial.inertia
    ET.SubElement(
        element,
        "inertia",
        {
            "ixx": format_float(tensor.ixx),
            "ixy": format_float(tensor.ixy),
            "ixz": format_float(tensor.ixz),
            "iyy": format_float(tensor.iyy),
            "iyz": format_float(tensor.iyz),
            "izz": format_float(tensor.izz),
        },
    )
    return element


def _geometry_element(geometry: Geometry, module_id: str, package_name: str) -> ET.Element:
    element = ET.Element("geometry")
    if isinstance(geometry, BoxGeometry):
        ET.SubElement(element, "box", {"size": format_vector(geometry.size)})
    elif isinstance(geometry, CylinderGeometry):
        ET.SubElement(
            element,
            "cylinder",
            {"radius": format_float(geometry.radius), "length": format_float(geometry.length)},
        )
    elif isinstance(geometry, SphereGeometry):
        ET.SubElement(element, "sphere", {"radius": format_float(geometry.radius)})
    elif isinstance(geometry, MeshGeometry):
        attributes = {"filename": mesh_uri(module_id, geometry.mesh, package_name)}
        if geometry.scale != (1.0, 1.0, 1.0):
            attributes["scale"] = format_vector(geometry.scale)
        ET.SubElement(element, "mesh", attributes)
    return element


def _joint_element(joint: ExpandedJoint) -> ET.Element:
    element = ET.Element("joint", {"name": joint.name, "type": joint.type})
    _append_origin(element, joint.origin)
    ET.SubElement(element, "parent", {"link": joint.parent})
    ET.SubElement(element, "child", {"link": joint.child})

    if joint.type != "fixed":
        ET.SubElement(element, "axis", {"xyz": format_vector(joint.axis)})
    if joint.limit is not None:
        ET.SubElement(
            element,
            "limit",
            {
                "lower": format_float(joint.limit.lower),
                "upper": format_float(joint.limit.upper),
                "effort": format_float(joint.limit.effort),
                "velocity": format_float(joint.limit.velocity),
            },
        )
    return element


def _append_origin(parent: ET.Element, origin: Origin) -> None:
    """Write an ``<origin>`` element, omitting it when it is the identity."""
    if origin.xyz == (0.0, 0.0, 0.0) and origin.rpy == (0.0, 0.0, 0.0):
        return
    ET.SubElement(
        parent,
        "origin",
        {"xyz": format_vector(origin.xyz), "rpy": format_vector(origin.rpy)},
    )
